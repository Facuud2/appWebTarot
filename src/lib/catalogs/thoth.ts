export const THOTH_CARDS: CanonicalCard[] = [
  ...THOTH_ATU_SEED.map(
    (atu): CanonicalCard => ({
      id: `thoth-major-${String(atu.rank).padStart(2, "0")}`,
      slug: atu.slug,
      arcana: "major",
      suit: null,
      rankNumber: atu.rank,
      romanNumeral: atu.roman,
      canonicalName: atu.nameEs,
      nameEn: atu.nameEn,
      deckTradition: "thoth",
      searchKeywords: Array.from(
        new Set([
          atu.nameEs,
          atu.nameEn,
          atu.roman,
          String(atu.rank),
          "Thoth",
          "Crowley",
          ...atu.keywords,
        ])
      ),
      traditionalUpright: atu.upright,
      traditionalReversed: atu.reversed,
      traditionalKeywords: atu.keywords,
      archetypeNote: `${atu.archetype} (Tarot de Thoth - Aleister Crowley & Frieda Harris).`,
    })
  ),
  ...THOTH_SUITS.flatMap((suitInfo) => {
    // 1 to 10
    const numbers: CanonicalCard[] = suitInfo.minors.map((m) => {
      const canonicalName = `${m.rank === 1 ? "As" : m.rank} de ${suitInfo.nameEs} - ${m.titleEs} (Thoth)`;
      const nameEn = `${m.rank === 1 ? "Ace" : m.rank} of ${suitInfo.nameEn} (${m.titleEn})`;
      return {
        id: `thoth-${suitInfo.suit}-${String(m.rank).padStart(2, "0")}`,
        slug: `thoth-${suitInfo.slug}-${String(m.rank).padStart(2, "0")}`,
        arcana: "minor",
        suit: suitInfo.suit,
        rankNumber: m.rank,
        romanNumeral: String(m.rank),
        canonicalName,
        nameEn,
        deckTradition: "thoth",
        searchKeywords: [
          canonicalName,
          nameEn,
          m.titleEs,
          m.titleEn,
          `${m.rank} de ${suitInfo.nameEs}`,
          `${m.rank} of ${suitInfo.nameEn}`,
          "Thoth",
          "Crowley",
        ],
        traditionalUpright: `Manifestación arquetípica de ${m.titleEs} en el reino de ${suitInfo.nameEs}.`,
        traditionalReversed: `Sombra, desvío o exceso de la fuerza de ${m.titleEs}.`,
        traditionalKeywords: [suitInfo.nameEs.toLowerCase(), m.titleEs.toLowerCase(), m.titleEn.toLowerCase(), "thoth"],
        archetypeNote: `Título esotérico: ${m.titleEn} (${m.titleEs}). Mazo Thoth.`,
      };
    });

    // 4 court cards (Princess, Prince, Queen, Knight)
    const courts: CanonicalCard[] = suitInfo.court.map((c) => {
      const canonicalName = `${c.labelEs} (Thoth)`;
      return {
        id: `thoth-${suitInfo.suit}-${String(c.rank).padStart(2, "0")}`,
        slug: `thoth-${suitInfo.slug}-${c.slugPart}`,
        arcana: "minor",
        suit: suitInfo.suit,
        rankNumber: c.rank,
        romanNumeral: c.slugPart.slice(0, 2).toUpperCase(),
        canonicalName,
        nameEn: c.labelEn,
        deckTradition: "thoth",
        searchKeywords: [
          canonicalName,
          c.labelEs,
          c.labelEn,
          c.element,
          "Thoth",
          "Crowley",
        ],
        traditionalUpright: `Fuerza subelemental pura: ${c.element} encarnada con dinamismo en la corte de ${suitInfo.nameEs}.`,
        traditionalReversed: `Desbalance o reactividad en la manifestación de ${c.element}.`,
        traditionalKeywords: [suitInfo.nameEs.toLowerCase(), c.element.toLowerCase(), "figura thoth"],
        archetypeNote: `${c.element} en el sistema ceremonial de Thoth.`,
      };
    });

    return [...numbers, ...courts];
  }),
];
